package net.protoform.core.call

import com.google.gson.{JsonElement, JsonParser}
import net.protoform.core.auth.MetadataHeader
import net.protoform.core.model.EndpointTarget
import net.protoform.core.schema.{MethodSchema, RpcPattern, ServiceSchema}

import scala.collection.mutable.ListBuffer
import scala.jdk.CollectionConverters._
import scala.util.control.NonFatal

enum PythonExportMode {
  case Stubs
  case Reflection
}

final case class PythonExportConfig(
  mode: PythonExportMode = PythonExportMode.Stubs,
  modulePrefix: String = "",
  includeComments: Boolean = true,
  streamPayloads: List[String] = Nil
)

object GrpcurlFormatter {

  def format(
    target: EndpointTarget,
    method: MethodSchema,
    resolvedPayload: String,
    resolvedHeaders: List[MetadataHeader]
  ): String = {
    val tlsFlags = List(
      if (!target.useTls) "-plaintext"
      else if (target.insecureSkipTlsVerify) "-insecure"
      else target.tlsCertPath.map(_.trim).filter(_.nonEmpty).map(p => s"""-cacert "$p"""").getOrElse(""),
      if (target.useTls) target.clientCertPath.map(_.trim).filter(_.nonEmpty).map(p => s"""-cert "$p"""").getOrElse("") else "",
      if (target.useTls) target.clientKeyPath.map(_.trim).filter(_.nonEmpty).map(p => s"""-key "$p"""").getOrElse("") else "",
      if (target.useTls) target.overrideAuthority.map(_.trim).filter(_.nonEmpty).map(a => s"""-authority "$a"""").getOrElse("") else ""
    ).filter(_.nonEmpty).mkString(" ")

    val headerFlags = resolvedHeaders
      .filter(_.enabled)
      .map(h => s"""-H "${h.key}: ${h.value}"""")
      .mkString(" ")

    val compactPayload = resolvedPayload.replaceAll("\\s+", " ").trim.replace("'", "'\\''")
    val targetHost = s"${if (target.host.contains(":")) s"[${target.host}]" else target.host}:${target.port}"
    List(
      "grpcurl",
      tlsFlags.trim,
      headerFlags,
      s"-d '$compactPayload'",
      targetHost,
      method.fullMethodName
    ).filter(_.nonEmpty).mkString(" ")
  }
}

object PythonSnippetGenerator {

  def inferStubModules(
    protoFile: Option[String],
    serviceFullName: String,
    modulePrefixOverride: String = ""
  ): (String, String, Option[String]) = {
    val normalizedFile = protoFile.map(_.replace('\\', '/').trim).filter(_.nonEmpty)
    val baseName = normalizedFile match {
      case Some(path) =>
        val leaf = path.split('/').lastOption.getOrElse("service.proto")
        val stem = if (leaf.endsWith(".proto")) leaf.dropRight(6) else leaf
        sanitizeModuleIdent(stem)
      case None =>
        val simple = serviceFullName.split('.').lastOption.getOrElse("service")
        camelToSnake(simple)
    }

    val inferredPkg = normalizedFile.flatMap { path =>
      val idx = path.lastIndexOf('/')
      if (idx > 0) Some(path.substring(0, idx).split('/').map(sanitizeModuleIdent).filter(_.nonEmpty).mkString("."))
      else None
    }.filter(_.nonEmpty)

    val overrideTrimmed = Option(modulePrefixOverride).map(_.trim).filter(_.nonEmpty)
    (s"${baseName}_pb2", s"${baseName}_pb2_grpc", overrideTrimmed.orElse(inferredPkg))
  }

  def generate(
    target: EndpointTarget,
    method: MethodSchema,
    service: Option[ServiceSchema],
    requestJson: String,
    headers: List[MetadataHeader],
    callOptions: RpcCallOptions,
    config: PythonExportConfig = PythonExportConfig()
  ): String = {
    val enabledHeaders = headers.filter(_.enabled)
    val hasBinaryHeaders = enabledHeaders.exists(_.isBinary)
    val hasCertReads = target.useTls && (
      target.tlsCertPath.exists(_.trim.nonEmpty) ||
        target.clientCertPath.exists(_.trim.nonEmpty) ||
        target.clientKeyPath.exists(_.trim.nonEmpty)
      )

    val payloads = resolvePayloads(method.pattern, requestJson, config.streamPayloads)
    val out = ListBuffer.empty[String]

    if (config.includeComments) {
      out += s"# Generated by ProtoForm for ${method.fullMethodName} (${method.pattern.label})"
    }

    val needsJsonFallback = payloads.exists(p => parseJsonSafe(p).isEmpty)
    if (hasBinaryHeaders) out += "import base64"
    if (needsJsonFallback) out += "import json"
    if (hasCertReads) out += "from pathlib import Path"
    out += "import grpc"

    config.mode match {
      case PythonExportMode.Stubs =>
        out += "from google.protobuf.json_format import MessageToJson, ParseDict"
        val (pb2Mod, pb2GrpcMod, pkgOpt) =
          inferStubModules(service.flatMap(_.protoFile), method.serviceFullName, config.modulePrefix)
        pkgOpt match {
          case Some(pkg) => out += s"from $pkg import $pb2Mod, $pb2GrpcMod"
          case None      => out += s"import $pb2Mod" ; out += s"import $pb2GrpcMod"
        }
        out += ""
        appendChannelBlock(out, target, config.includeComments)
        appendMetadataBlock(out, enabledHeaders)
        appendStubCallBlock(out, method, service, pb2Mod, pb2GrpcMod, payloads, callOptions)

      case PythonExportMode.Reflection =>
        out += "from google.protobuf.descriptor_pool import DescriptorPool"
        out += "from google.protobuf.json_format import MessageToJson, ParseDict"
        out += "from google.protobuf.message_factory import GetMessageClass"
        out += "from grpc_reflection.v1alpha.proto_reflection_descriptor_database import ProtoReflectionDescriptorDatabase"
        out += ""
        appendChannelBlock(out, target, config.includeComments)
        appendMetadataBlock(out, enabledHeaders)
        appendReflectionCallBlock(out, method, payloads, callOptions)
    }

    out.mkString("\n")
  }

  private def appendChannelBlock(out: ListBuffer[String], target: EndpointTarget, includeComments: Boolean): Unit = {
    val hostPort = s"${if (target.host.contains(":")) s"[${target.host}]" else target.host}:${target.port}"
    val channelOptions = ListBuffer.empty[String]
    if (target.useTls) {
      target.overrideAuthority.map(_.trim).filter(_.nonEmpty).foreach { auth =>
        channelOptions += s"""("grpc.ssl_target_name_override", ${pyString(auth)})"""
      }
    }
    val optsArg = if (channelOptions.nonEmpty) s", options=[${channelOptions.mkString(", ")}]" else ""

    if (!target.useTls) {
      out += s"channel = grpc.insecure_channel(${pyString(hostPort)}$optsArg)"
    } else {
      if (target.insecureSkipTlsVerify && includeComments) {
        out += "# Note: ProtoForm insecureSkipTlsVerify was enabled; grpcio validates TLS certs unless a CA cert is supplied."
      }
      val rootArg = target.tlsCertPath.map(_.trim).filter(_.nonEmpty)
        .map(p => s"root_certificates=Path(${pyString(p)}).read_bytes()")
      val keyArg = target.clientKeyPath.map(_.trim).filter(_.nonEmpty)
        .map(p => s"private_key=Path(${pyString(p)}).read_bytes()")
      val certArg = target.clientCertPath.map(_.trim).filter(_.nonEmpty)
        .map(p => s"certificate_chain=Path(${pyString(p)}).read_bytes()")
      val credArgs = List(rootArg, keyArg, certArg).flatten

      if (credArgs.isEmpty) {
        out += "credentials = grpc.ssl_channel_credentials()"
      } else {
        out += "credentials = grpc.ssl_channel_credentials("
        credArgs.zipWithIndex.foreach { case (arg, idx) =>
          val comma = if (idx < credArgs.size - 1) "," else ""
          out += s"    $arg$comma"
        }
        out += ")"
      }
      out += s"channel = grpc.secure_channel(${pyString(hostPort)}, credentials$optsArg)"
    }
    out += ""
  }

  private def appendMetadataBlock(out: ListBuffer[String], headers: List[MetadataHeader]): Unit = {
    if (headers.isEmpty) {
      out += "metadata = []"
    } else {
      out += "metadata = ["
      headers.foreach { h =>
        val valueExpr = if (h.isBinary) s"base64.b64decode(${pyString(h.value)})" else pyString(h.value)
        out += s"    (${pyString(h.key)}, $valueExpr),"
      }
      out += "]"
    }
    out += ""
  }

  private def appendStubCallBlock(
    out: ListBuffer[String],
    method: MethodSchema,
    service: Option[ServiceSchema],
    pb2Mod: String,
    pb2GrpcMod: String,
    payloads: List[String],
    callOptions: RpcCallOptions
  ): Unit = {
    val svcSimple = service.map(_.simpleName).getOrElse(
      method.serviceFullName.split('.').lastOption.getOrElse("Service")
    )
    val inputMsgName = method.inputSchema.simpleName
    val callKwargs = buildCallKwargs(callOptions)

    out += s"stub = $pb2GrpcMod.${svcSimple}Stub(channel)"
    method.pattern match {
      case RpcPattern.Unary =>
        appendSinglePayload(out, payloads.headOption.getOrElse("{}"), indent = "")
        out += s"request = ParseDict(payload, $pb2Mod.$inputMsgName())"
        out += s"response = stub.${method.name}(request$callKwargs)"
        out += s"print(MessageToJson(response, preserving_proto_field_name=${pyBool(callOptions.preserveProtoFieldNames)}))"

      case RpcPattern.ServerStreaming =>
        appendSinglePayload(out, payloads.headOption.getOrElse("{}"), indent = "")
        out += s"request = ParseDict(payload, $pb2Mod.$inputMsgName())"
        out += s"for response in stub.${method.name}(request$callKwargs):"
        out += s"    print(MessageToJson(response, preserving_proto_field_name=${pyBool(callOptions.preserveProtoFieldNames)}))"

      case RpcPattern.ClientStreaming =>
        appendPayloadList(out, payloads)
        out += ""
        out += "def request_stream():"
        out += "    for item in payloads:"
        out += s"        yield ParseDict(item, $pb2Mod.$inputMsgName())"
        out += ""
        out += s"response = stub.${method.name}(request_stream()$callKwargs)"
        out += s"print(MessageToJson(response, preserving_proto_field_name=${pyBool(callOptions.preserveProtoFieldNames)}))"

      case RpcPattern.BidirectionalStreaming =>
        appendPayloadList(out, payloads)
        out += ""
        out += "def request_stream():"
        out += "    for item in payloads:"
        out += s"        yield ParseDict(item, $pb2Mod.$inputMsgName())"
        out += ""
        out += s"for response in stub.${method.name}(request_stream()$callKwargs):"
        out += s"    print(MessageToJson(response, preserving_proto_field_name=${pyBool(callOptions.preserveProtoFieldNames)}))"
    }
  }

  private def appendReflectionCallBlock(
    out: ListBuffer[String],
    method: MethodSchema,
    payloads: List[String],
    callOptions: RpcCallOptions
  ): Unit = {
    val callKwargs = buildCallKwargs(callOptions)
    val grpcMethodFactory = method.pattern match {
      case RpcPattern.Unary                  => "unary_unary"
      case RpcPattern.ServerStreaming        => "unary_stream"
      case RpcPattern.ClientStreaming        => "stream_unary"
      case RpcPattern.BidirectionalStreaming => "stream_stream"
    }

    out += "reflection_db = ProtoReflectionDescriptorDatabase(channel)"
    out += "desc_pool = DescriptorPool(reflection_db)"
    out += s"service_desc = desc_pool.FindServiceByName(${pyString(method.serviceFullName)})"
    out += s"method_desc = service_desc.FindMethodByName(${pyString(method.name)})"
    out += "req_cls = GetMessageClass(method_desc.input_type)"
    out += "resp_cls = GetMessageClass(method_desc.output_type)"
    out += ""
    out += s"rpc_call = channel.$grpcMethodFactory("
    out += s"    ${pyString(s"/${method.serviceFullName}/${method.name}")},"
    out += "    request_serializer=lambda msg: msg.SerializeToString(),"
    out += "    response_deserializer=resp_cls.FromString,"
    out += ")"
    out += ""

    method.pattern match {
      case RpcPattern.Unary =>
        appendSinglePayload(out, payloads.headOption.getOrElse("{}"), indent = "")
        out += "request = ParseDict(payload, req_cls())"
        out += s"response = rpc_call(request$callKwargs)"
        out += s"print(MessageToJson(response, preserving_proto_field_name=${pyBool(callOptions.preserveProtoFieldNames)}))"

      case RpcPattern.ServerStreaming =>
        appendSinglePayload(out, payloads.headOption.getOrElse("{}"), indent = "")
        out += "request = ParseDict(payload, req_cls())"
        out += s"for response in rpc_call(request$callKwargs):"
        out += s"    print(MessageToJson(response, preserving_proto_field_name=${pyBool(callOptions.preserveProtoFieldNames)}))"

      case RpcPattern.ClientStreaming =>
        appendPayloadList(out, payloads)
        out += ""
        out += "def request_stream():"
        out += "    for item in payloads:"
        out += "        yield ParseDict(item, req_cls())"
        out += ""
        out += s"response = rpc_call(request_stream()$callKwargs)"
        out += s"print(MessageToJson(response, preserving_proto_field_name=${pyBool(callOptions.preserveProtoFieldNames)}))"

      case RpcPattern.BidirectionalStreaming =>
        appendPayloadList(out, payloads)
        out += ""
        out += "def request_stream():"
        out += "    for item in payloads:"
        out += "        yield ParseDict(item, req_cls())"
        out += ""
        out += s"for response in rpc_call(request_stream()$callKwargs):"
        out += s"    print(MessageToJson(response, preserving_proto_field_name=${pyBool(callOptions.preserveProtoFieldNames)}))"
    }
  }

  private def buildCallKwargs(callOptions: RpcCallOptions): String = {
    val parts = ListBuffer("metadata=metadata")
    if (callOptions.deadlineSeconds > 0) {
      parts += s"timeout=${callOptions.deadlineSeconds}"
    }
    if (callOptions.useGzipCompression) {
      parts += "compression=grpc.Compression.Gzip"
    }
    s", ${parts.mkString(", ")}"
  }

  private def resolvePayloads(pattern: RpcPattern, requestJson: String, streamPayloads: List[String]): List[String] = {
    val isClientStream = pattern == RpcPattern.ClientStreaming || pattern == RpcPattern.BidirectionalStreaming
    val cleanedStream = streamPayloads.map(_.trim).filter(_.nonEmpty)
    if (isClientStream && cleanedStream.nonEmpty) cleanedStream
    else List(Option(requestJson).map(_.trim).filter(_.nonEmpty).getOrElse("{}"))
  }

  private def appendSinglePayload(out: ListBuffer[String], rawJson: String, indent: String): Unit = {
    val expr = parseJsonSafe(rawJson) match {
      case Some(el) => toPythonLiteral(el, indentLevel = 0)
      case None     => s"json.loads(${pyString(rawJson)})"
    }
    out += s"${indent}payload = $expr"
  }

  private def appendPayloadList(out: ListBuffer[String], payloads: List[String]): Unit = {
    out += "payloads = ["
    payloads.foreach { rawJson =>
      val expr = parseJsonSafe(rawJson) match {
        case Some(el) => toPythonLiteral(el, indentLevel = 1)
        case None     => s"json.loads(${pyString(rawJson)})"
      }
      out += s"    $expr,"
    }
    out += "]"
  }

  private def parseJsonSafe(raw: String): Option[JsonElement] = {
    try {
      Some(JsonParser.parseString(raw))
    } catch {
      case NonFatal(_) => None
    }
  }

  private def toPythonLiteral(el: JsonElement, indentLevel: Int): String = {
    val indent = "    " * indentLevel
    val childIndent = "    " * (indentLevel + 1)
    if (el == null || el.isJsonNull) {
      "None"
    } else if (el.isJsonPrimitive) {
      val prim = el.getAsJsonPrimitive
      if (prim.isBoolean) pyBool(prim.getAsBoolean)
      else if (prim.isNumber) prim.getAsString
      else pyString(prim.getAsString)
    } else if (el.isJsonArray) {
      val arr = el.getAsJsonArray.asScala.toList
      if (arr.isEmpty) "[]"
      else {
        val items = arr.map(item => s"$childIndent${toPythonLiteral(item, indentLevel + 1)}")
        s"[\n${items.mkString(",\n")},\n$indent]"
      }
    } else {
      val entries = el.getAsJsonObject.entrySet().asScala.toList
      if (entries.isEmpty) "{}"
      else {
        val pairs = entries.map { e =>
          s"$childIndent${pyString(e.getKey)}: ${toPythonLiteral(e.getValue, indentLevel + 1)}"
        }
        s"{\n${pairs.mkString(",\n")},\n$indent}"
      }
    }
  }

  private def pyBool(b: Boolean): String = if (b) "True" else "False"

  private def pyString(s: String): String = {
    val sb = new StringBuilder("\"")
    Option(s).getOrElse("").foreach {
      case '\\' => sb.append("\\\\")
      case '"'  => sb.append("\\\"")
      case '\n' => sb.append("\\n")
      case '\r' => sb.append("\\r")
      case '\t' => sb.append("\\t")
      case c if c < ' ' => sb.append(f"\\x${c.toInt}%02x")
      case c    => sb.append(c)
    }
    sb.append('"').toString()
  }

  private def sanitizeModuleIdent(raw: String): String = {
    val cleaned = raw.replaceAll("[^A-Za-z0-9_]", "_").replaceAll("^_+|_+$", "")
    if (cleaned.isEmpty) "service"
    else if (cleaned.head.isDigit) s"_$cleaned"
    else cleaned
  }

  private def camelToSnake(name: String): String = {
    val snake = name.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase
    sanitizeModuleIdent(snake)
  }
}
